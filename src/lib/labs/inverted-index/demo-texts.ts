export interface DemoOptions {
  /** Number of documents (default 100 — as required by the task). */
  count?: number;
  /** Minimum number of words per document. */
  minWords?: number;
}

/**
 * Generates the demo collection: documents across four themes, each with at
 * least `minWords` words.
 */
export function generateDemoCollection(options: DemoOptions = {}): DocumentSource[] {
  const { count = 100, minWords = 1000 } = options;
  const perThemeCounter = Array.from({ length: THEMES.length }, () => 0);
  const sources: DocumentSource[] = [];

  for (let i = 0; i < count; i++) {
    const themeIndex = i % THEMES.length;
    const theme = THEMES[themeIndex];
    const rng = mulberry32(0x1234567 + i * 7919);

    const parts: string[] = [theme.opening.replace("{n}", String(i + 1))];
    const pool = [...theme.sentences, ...theme.sentences, ...SHARED_SENTENCES];

    let wordCount = parts[0].split(" ").length;
    while (wordCount < minWords) {
      const sentence = fill(pick(rng, pool), rng);
      parts.push(sentence);
      wordCount += sentence.split(" ").length;
    }
    parts.push(theme.closing);

    const text = parts.join(" ");
    const number = String(perThemeCounter[themeIndex] + 1).padStart(2, "0");
    perThemeCounter[themeIndex] += 1;
    const name = `${theme.slug}_${number}.txt`;

    sources.push({ name, path: `demo/${name}`, read: async () => text });
  }

  return sources;
}
