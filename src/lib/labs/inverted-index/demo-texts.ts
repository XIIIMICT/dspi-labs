/** Deterministic PRNG (mulberry32) — the collection is reproducible. */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pick<T>(rng: () => number, items: T[]): T {
  return items[Math.floor(rng() * items.length)];
}

/** Slots for sentence templates (agreement is baked into each template). */
const SLOTS = {
  big: ["тысячи", "миллионы", "сотни тысяч"],
  sys: ["поисковая система", "информационная система", "рекомендательная система"],
  sysp: ["поисковые системы", "распределённые системы", "информационные системы"],
  ms: ["миллисекунды", "доли секунды", "секунды"],
  often: ["ежедневно", "ежечасно", "постоянно", "непрерывно"],
  num: ["десять", "двадцать", "пятьдесят", "сто"],
} as const;

function fill(sentence: string, rng: () => number): string {
  return sentence.replace(/\{(\w+)\}/g, (_, key: string) => {
    const options = (SLOTS as Record<string, readonly string[]>)[key];
    return options ? pick(rng, [...options]) : key;
  });
}

